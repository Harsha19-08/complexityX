export function Patterns({ a }: { a: Analysis }) {
  if (!a.patterns.length) return <p className="text-sm text-muted">No standard DSA pattern stood out.</p>;
  return (
    <div className="grid gap-2.5 sm:grid-cols-2">
      {a.patterns.map((p, i) => {
        const slug = patternSlug(p.name);
        const inner = (
          <>
            <div className="flex items-center gap-2">
              <span className="text-sm font-medium">{p.name}</span>
              <Badge tone={p.status === "detected" ? "good" : "accent"}>{p.status === "detected" ? "Used" : "Try this"}</Badge>
            </div>
            {p.why && <p className="mt-1 text-[13px] leading-relaxed text-muted">{p.why}</p>}
          </>
        );
        return slug ? (
          <Link key={i} href={`/patterns/${slug}`} className="rounded-lg border border-line bg-surface-2/40 p-3 transition-colors hover:border-accent/50">{inner}</Link>
        ) : (
          <div key={i} className="rounded-lg border border-line bg-surface-2/40 p-3">{inner}</div>
        );
      })}
    </div>
  );
}

