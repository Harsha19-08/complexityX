export function Hints({ hints, revealed, onReveal }: { hints: string[]; revealed: number; onReveal: () => void }) {
  return (
    <div className="space-y-2">
      {hints.slice(0, revealed).map((h, i) => (
        <div key={i} className="flex gap-2.5 rounded-lg border border-accent/25 bg-accent/5 p-3 text-[13px] leading-relaxed animate-rise">
          <Lightbulb className="mt-0.5 h-4 w-4 shrink-0 text-accent" aria-hidden />
          <div><span className="font-medium">Hint {i + 1}. </span>{h}</div>
        </div>
      ))}
      {revealed < hints.length && (
        <Button variant="secondary" size="sm" onClick={onReveal}><Lightbulb className="h-3.5 w-3.5" /> {revealed === 0 ? "Show first hint" : "Next hint"} ({revealed}/{hints.length})</Button>
      )}
    </div>
  );
}

export function OptimizedCode({ a, language }: { a: Analysis; language: Language }) {
  const [copied, setCopied] = React.useState(false);
  const [explain, setExplain] = React.useState(false);
  const code = a.optimizedCode;
  if (!code) {
    return <p className="text-sm text-muted">Concrete optimized code is generated by the AI engine. Connect a provider in Settings to get it; the approaches above still apply.</p>;
  }
  const copy = async () => {
    try { await navigator.clipboard.writeText(code); setCopied(true); setTimeout(() => setCopied(false), 1400); } catch { /* clipboard blocked */ }
  };
  const download = () => {
    const url = URL.createObjectURL(new Blob([code + "\n"], { type: "text/plain" }));
    const el = document.createElement("a");
    el.href = url; el.download = languageMeta(language).file; el.click();
    URL.revokeObjectURL(url);
  };
  return (
    <div>
      <div className="mb-2 flex flex-wrap gap-2">
        <Button variant="secondary" size="sm" onClick={copy}>{copied ? <Check className="h-3.5 w-3.5 text-good" /> : <Copy className="h-3.5 w-3.5" />}{copied ? "Copied" : "Copy"}</Button>
        <Button variant="secondary" size="sm" onClick={download}><Download className="h-3.5 w-3.5" /> Download</Button>
        {a.codeExplanation.length > 0 && <Button variant="secondary" size="sm" onClick={() => setExplain((v) => !v)} aria-expanded={explain}><Sparkles className="h-3.5 w-3.5" /> Explain code</Button>}
      </div>
      <CodeBlock code={code} language={language} maxHeight={360} label="Optimized code" />
      {explain && (
        <ul className="mt-3 list-disc space-y-1 pl-5 text-[13px] leading-relaxed text-muted animate-rise">
          {a.codeExplanation.map((x, i) => <li key={i}>{x}</li>)}
        </ul>
      )}
    </div>
  );
}

export function Comparison({ a }: { a: Analysis }) {
  const cT = a.timeComplexity.value, cS = a.spaceComplexity.value;
  const oT = a.comparison.optimizedTime, oS = a.comparison.optimizedSpace;
  const better = isImprovement(cT, oT);
  const Row = ({ label, from, to }: { label: string; from: string; to: string }) => (
    <div className="flex items-center gap-3 py-2">
      <div className="w-14 text-[13px] text-muted">{label}</div>
      <span className={cn("font-mono text-sm", TONE_TEXT[toneOf(from)])}>{from}</span>
      <ArrowRight className="h-3.5 w-3.5 text-muted" aria-label="becomes" />
      <span className={cn("font-mono text-sm font-semibold", TONE_TEXT[toneOf(to)])}>{to}</span>
    </div>
  );
  return (
    <div>
      <div className="divide-y divide-line rounded-lg border border-line px-3">
        <Row label="Time" from={cT} to={oT} />
        <Row label="Space" from={cS} to={oS} />
      </div>
      {a.optimization.whyFaster && <p className="mt-3 text-[13px] leading-relaxed text-muted">{a.optimization.whyFaster}</p>}
      {a.comparison.tradeoff && <p className="mt-2 text-[13px] leading-relaxed"><span className="font-medium">Trade-off. </span><span className="text-muted">{a.comparison.tradeoff}</span></p>}
      {!better && <p className="mt-2 text-xs text-muted">Time complexity stays in the same class.</p>}
    </div>
  );
}

export function OptimalityBanner({ a }: { a: Analysis }) {
  const o = a.optimization;
  const label = o.optimalityKind === "provably_optimal" ? "Provably optimal" : o.optimalityKind === "assumption_dependent" ? "Optimal under assumptions" : "Best known";
  return (
    <div className="mb-3 flex flex-wrap items-center gap-2 rounded-lg border border-line bg-surface-2/40 p-3 text-[13px]">
      <Badge tone={o.canImprove ? "warn" : "good"}>{o.canImprove ? "Room to improve" : label}</Badge>
      {o.canImprove && o.targetTime && <span className="text-muted">Target <span className="font-mono text-fg">{o.targetTime}</span> time, <span className="font-mono text-fg">{o.targetSpace}</span> space</span>}
      {o.optimalityNote && <p className="basis-full text-muted">{o.optimalityNote}</p>}
      {o.optimalityKind === "assumption_dependent" && o.assumptions.length > 0 && (
        <ul className="basis-full list-disc pl-5 text-muted">{o.assumptions.map((x, i) => <li key={i}>{x}</li>)}</ul>
      )}
    </div>
  );
}

